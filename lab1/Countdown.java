public class Countdown {
    public static void main(String[] args) {

        // while loop
        int number = 10;

        while (number >= 1) {
            System.out.println(number);
            number--;
        }

        System.out.println("Lift off!");

        System.out.println();

        // for loop
        for (int i = 10; i >= 1; i--) {
            System.out.println(i);
        }

        System.out.println("Lift off!");
    }
}
